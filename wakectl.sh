# Disclaimer: 100% of this script was written via LLM (Claude). 
#
# wakectl - see which devices can wake this machine from sleep (by readable
# name), disable/enable them, and persist the choice across reboots.
#
#   sudo wakectl          interactive mode
#   wakectl list          print the device table and exit (no root needed)
#
# Sources:  ACPI (/proc/acpi/wakeup: lid, power button, controllers...),
#           USB and PCI devices (sysfs power/wakeup).
# Persistence: USB/PCI -> udev rules; ACPI -> a small systemd oneshot unit.
# Deps: bash 4+, pciutils (lspci). Optional: usbutils (lsusb) for USB names.

set -u
RULES_FILE=/etc/udev/rules.d/90-disable-wake.rules
UNIT_NAME=wakectl-acpi.service
UNIT_FILE=/etc/systemd/system/$UNIT_NAME
ACPI_FILE=${WAKECTL_ACPI_FILE:-/proc/acpi/wakeup}
declare -A RULES=()   # key -> device name. Key is a udev rule line, or "acpi:NAME"
DIRTY=0               # 1 = in-memory choices differ from what is on disk

if [[ -t 1 ]]; then
  RED=$'\e[31m'; GRN=$'\e[32m'; DIM=$'\e[2m'; BLD=$'\e[1m'; RST=$'\e[0m'
else
  RED=; GRN=; DIM=; BLD=; RST=
fi

usage() {
  cat <<USAGE
Usage: sudo wakectl        interactive mode
       wakectl list        show wake-capable devices and exit

Interactive commands:
  <numbers>   toggle those devices, e.g. "2 5 7" (applies immediately)
  s           save choices: udev rules ($RULES_FILE)
              and, for ACPI entries, $UNIT_NAME
  r           rescan devices
  q           quit
USAGE
}

# ---------- persistence ----------
rules_del() { # delete one key (unset is unreliable with quotes in the key)
  local k; local -A keep=()
  for k in "${!RULES[@]}"; do [[ $k != "$1" ]] && keep[$k]=${RULES[$k]}; done
  RULES=()
  for k in "${!keep[@]}"; do RULES[$k]=${keep[$k]}; done
}

load_rules() {
  RULES=(); DIRTY=0
  local line name="" rest
  if [[ -f $RULES_FILE ]]; then
    while IFS= read -r line; do
      case $line in
        "##"*) ;;
        "# "*) name=${line#\# } ;;
        ACTION*) RULES[$line]=$name; name="" ;;
      esac
    done < "$RULES_FILE"
  fi
  if [[ -f $UNIT_FILE ]]; then
    while IFS= read -r line; do
      if [[ $line == "# wakectl: "* ]]; then
        rest=${line#\# wakectl: }          # NAME|friendly name
        RULES["acpi:${rest%%|*}"]=${rest#*|}
      fi
    done < "$UNIT_FILE"
  fi
}

save_rules() {
  local r name
  local -a udev=() acpi=()
  for r in "${!RULES[@]}"; do
    if [[ $r == acpi:* ]]; then acpi+=("$r"); else udev+=("$r"); fi
  done

  # --- USB / PCI: udev rules ---
  if ((${#udev[@]} == 0)); then
    rm -f "$RULES_FILE"
  else
    {
      echo "## Generated by wakectl: disables wake-from-sleep for the devices below."
      echo "## Re-run 'sudo wakectl' to change, or delete this file to undo."
      printf '%s\n' "${udev[@]}" | sort | while IFS= read -r r; do
        echo "# ${RULES[$r]}"
        echo "$r"
      done
    } > "$RULES_FILE"
  fi
  udevadm control --reload 2>/dev/null
  echo "udev:    ${#udev[@]} rule(s) -> $RULES_FILE"

  # --- ACPI: systemd oneshot (udev cannot set these) ---
  if ((${#acpi[@]} == 0)); then
    if [[ -f $UNIT_FILE ]]; then
      systemctl disable "$UNIT_NAME" >/dev/null 2>&1
      rm -f "$UNIT_FILE"; systemctl daemon-reload
    fi
  else
    {
      echo "# Generated by wakectl. Disables selected ACPI wake sources at boot."
      echo "# Re-run 'sudo wakectl' to change, or disable/remove this unit to undo."
      echo "[Unit]"
      echo "Description=Disable selected ACPI wake sources (managed by wakectl)"
      echo
      echo "[Service]"
      echo "Type=oneshot"
      echo "RemainAfterExit=yes"
      printf '%s\n' "${acpi[@]}" | sort | while IFS= read -r r; do
        name=${r#acpi:}
        echo "# wakectl: $name|${RULES[$r]}"
        echo "ExecStart=/bin/sh -c 'grep -q \"^$name[[:space:]].*[*]enabled\" /proc/acpi/wakeup && echo $name > /proc/acpi/wakeup || true'"
      done
      echo
      echo "[Install]"
      echo "WantedBy=multi-user.target"
    } > "$UNIT_FILE"
    systemctl daemon-reload
    systemctl enable "$UNIT_NAME" >/dev/null 2>&1
  fi
  echo "systemd: ${#acpi[@]} ACPI source(s) -> $UNIT_FILE"
  DIRTY=0
}

# ---------- device discovery ----------
# DEV_PATH is a sysfs power/wakeup file, or "acpi:NAME" for /proc/acpi/wakeup entries.
DEV_PATH=(); DEV_TYPE=(); DEV_NAME=(); DEV_ID=(); DEV_RULE=()

usb_name() { # sysfs-dir vid pid
  local d=$1 m="" p=""
  [[ -r $d/manufacturer ]] && m=$(<"$d/manufacturer")
  [[ -r $d/product ]] && p=$(<"$d/product")
  [[ -n $m && $p == "$m"* ]] && m=""
  if [[ -n $p ]]; then
    echo "${m:+$m }$p"
  elif command -v lsusb >/dev/null; then
    lsusb -d "$2:$3" | head -1 | sed -E 's/^Bus [0-9]+ Device [0-9]+: ID [0-9a-f:]+ ?//'
  fi
}

acpi_name() { # sysfs-node column of /proc/acpi/wakeup, e.g. platform:PNP0C0D:00
  local node=$1 id n=""
  case $node in
    "") echo "ACPI wake source (no device attached)" ;;
    pci:*)
      command -v lspci >/dev/null && \
        n=$(lspci -s "${node#pci:}" 2>/dev/null | sed -E 's/^[^ ]+ //; s/ \(rev [0-9a-f]+\)//')
      echo "${n:-PCI device ${node#pci:}}" ;;
    *:*)
      id=${node#*:}
      case ${id%%:*} in
        PNP0C0D) echo "Laptop lid (opening it wakes the machine)" ;;
        PNP0C0C) echo "Power button" ;;
        PNP0C0E) echo "Sleep button" ;;
        PNP0303|PNP030B) echo "PS/2 keyboard" ;;
        PNP0F13|PNP0F03) echo "PS/2 mouse / touchpad" ;;
        *) echo "ACPI device $id" ;;
      esac ;;
    *) echo "$node" ;;
  esac
}

scan_acpi() {
  [[ -r $ACPI_FILE ]] || return 0
  local name sstate status node
  while read -r name sstate status node; do
    [[ -z $name || $name == Device ]] && continue
    DEV_PATH+=("acpi:$name"); DEV_TYPE+=("ACPI"); DEV_NAME+=("$(acpi_name "$node")")
    DEV_ID+=("$name/$sstate"); DEV_RULE+=("acpi:$name")
  done < "$ACPI_FILE"
}

scan() {
  DEV_PATH=(); DEV_TYPE=(); DEV_NAME=(); DEV_ID=(); DEV_RULE=()
  local d w vid pid name slot base tag

  scan_acpi

  for d in /sys/bus/usb/devices/*; do
    [[ -f $d/idVendor && -f $d/power/wakeup ]] || continue
    w=$d/power/wakeup
    [[ -n $(cat "$w" 2>/dev/null) ]] || continue
    vid=$(<"$d/idVendor"); pid=$(<"$d/idProduct")
    name=$(usb_name "$d" "$vid" "$pid"); : "${name:=Unknown USB device}"
    base=$(basename "$d"); tag=USB
    [[ $base =~ ^usb[0-9]+$ ]] && tag="USB hub"   # root hub: gates every device under it
    DEV_PATH+=("$w"); DEV_TYPE+=("$tag"); DEV_NAME+=("$name"); DEV_ID+=("$vid:$pid")
    DEV_RULE+=("ACTION==\"add\", SUBSYSTEM==\"usb\", ENV{DEVTYPE}==\"usb_device\", ATTR{idVendor}==\"$vid\", ATTR{idProduct}==\"$pid\", ATTR{power/wakeup}=\"disabled\"")
  done

  for d in /sys/bus/pci/devices/*; do
    [[ -f $d/power/wakeup ]] || continue
    w=$d/power/wakeup
    [[ -n $(cat "$w" 2>/dev/null) ]] || continue
    slot=$(basename "$d")
    name=""
    command -v lspci >/dev/null && \
      name=$(lspci -s "$slot" 2>/dev/null | sed -E 's/^[^ ]+ //; s/ \(rev [0-9a-f]+\)//')
    : "${name:=Unknown PCI device}"
    DEV_PATH+=("$w"); DEV_TYPE+=("PCI"); DEV_NAME+=("$name"); DEV_ID+=("$slot")
    DEV_RULE+=("ACTION==\"add\", SUBSYSTEM==\"pci\", KERNEL==\"$slot\", ATTR{power/wakeup}=\"disabled\"")
  done
}

# ---------- state read/write ----------
get_state() { # index -> "enabled" | "disabled"
  local p=${DEV_PATH[$1]}
  if [[ $p == acpi:* ]]; then
    awk -v n="${p#acpi:}" '$1==n {gsub(/[*]/,"",$3); print $3}' "$ACPI_FILE"
  else
    cat "$p"
  fi
}

set_state() { # index, want
  local i=$1 want=$2 p=${DEV_PATH[$1]}
  if [[ $p == acpi:* ]]; then
    # /proc/acpi/wakeup is a toggle: write the name only if the state differs
    [[ $(get_state "$i") == "$want" ]] && return 0
    echo "${p#acpi:}" > "$ACPI_FILE" 2>/dev/null
    [[ $(get_state "$i") == "$want" ]]
  else
    echo "$want" > "$p" 2>/dev/null
  fi
}

# ---------- display ----------
show() {
  local i st stc saved
  printf '\n%s%-3s %-9s %-6s %-8s %-54s %s%s\n' "$BLD" "#" "Wake" "Saved" "Type" "Device" "ID" "$RST"
  for i in "${!DEV_PATH[@]}"; do
    st=$(get_state "$i")
    if [[ $st == enabled ]]; then stc="${RED}enabled ${RST}"; else stc="${GRN}disabled${RST}"; fi
    saved="   "; [[ -n ${RULES[${DEV_RULE[$i]}]+x} ]] && saved="yes"
    printf '%-3s %s  %-6s %-8s %-54s %s%s%s\n' "$i" "$stc" "$saved" "${DEV_TYPE[$i]}" \
      "${DEV_NAME[$i]:0:54}" "$DIM" "${DEV_ID[$i]}" "$RST"
  done
  echo
  echo "${DIM}Wake: current state. Saved: persisted so it stays disabled after reboot.${RST}"
  echo "${DIM}ACPI and PCI/USB entries are separate switches; a device may need both disabled.${RST}"
  ((DIRTY)) && echo "${RED}* Unsaved changes: press 's' to persist them${RST}"
}

# ---------- actions ----------
toggle() {
  local i=$1 cur rule
  if ! [[ $i =~ ^[0-9]+$ ]] || ((i >= ${#DEV_PATH[@]})); then
    echo "  '$i' is not a valid device number"; return
  fi
  cur=$(get_state "$i"); rule=${DEV_RULE[$i]}
  if [[ $cur == enabled ]]; then
    if set_state "$i" disabled; then
      RULES[$rule]="${DEV_NAME[$i]} (${DEV_ID[$i]})"; DIRTY=1
      echo "  disabled wake: ${DEV_NAME[$i]}"
      [[ ${DEV_TYPE[$i]} == "USB hub" ]] && \
        echo "  ${RED}note:${RST} this is a root hub; no device behind it can wake the machine."
    else
      echo "  ${RED}failed${RST} to disable ${DEV_NAME[$i]}"
    fi
  else
    if set_state "$i" enabled; then
      rules_del "$rule"; DIRTY=1
      echo "  enabled wake:  ${DEV_NAME[$i]}"
    else
      echo "  ${RED}failed${RST} to enable ${DEV_NAME[$i]}"
    fi
  fi
}

interactive() {
  local input tok a
  load_rules
  while :; do
    scan; show
    read -rp "Numbers to toggle (s=save, r=rescan, q=quit, ?=help): " input || break
    for tok in $input; do
      case $tok in
        q|Q) if ((DIRTY)); then
               read -rp "Save unsaved changes first? [Y/n] " a
               [[ ${a:-y} =~ ^[Yy] ]] && save_rules
             fi
             return ;;
        s|S) save_rules ;;
        r|R) ;;
        '?'|h) usage ;;
        *) toggle "$tok" ;;
      esac
    done
  done
}

# ---------- main ----------
case "${1:-}" in
  list)      load_rules; scan; show ;;
  -h|--help) usage ;;
  "")        if [[ $EUID -ne 0 ]]; then exec sudo bash "$0" "$@"; fi; interactive ;;
  *)         usage; exit 1 ;;
esac
